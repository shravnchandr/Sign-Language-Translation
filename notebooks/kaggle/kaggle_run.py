"""Run a repo command as a Kaggle notebook (GPU or CPU) from the terminal.

Each run is its own private notebook `<user>/islr-<name>`, so every run keeps its
own outputs. The notebook clones this repo at a pinned commit (default: local
HEAD, which must be pushed), installs `lmdb`, finds the mounted datasets and runs

    python -m <module> <args>

with placeholders filled in:
    {IS_LMDB_DIR}  folder of is.lmdb.mdb + train.csv + sign map (shravnchandr/asl-is-lmdb)
    {CKPT_DIR}     root of shravnchandr/islr-checkpoints (fold0_graph/, phrases01/)
    {WLASL_DIR}    folder of wlasl.lmdb.mdb + train.csv (shravnchandr/wlasl-lmdb)
    {OUT}          /kaggle/working/out — everything written here is the run's output
The IS / WLASL LMDB folders are copied to local disk first (/kaggle/input is slow for
random reads); --no-copy reads them in place.
stdout/stderr also go to {OUT}/run.log.

Usage (from the repo root):
  python notebooks/kaggle/kaggle_run.py push phrases02 --gpu -- cnn_transformer.train_phrases \\
      --data-dir {IS_LMDB_DIR} --lmdb-path {IS_LMDB_DIR}/is.lmdb.mdb --val-fold 0 --arch graph \\
      --init {CKPT_DIR}/fold0_graph/best_phase1.pth --out-dir {OUT} --num-workers 4
  python notebooks/kaggle/kaggle_run.py status phrases02
  python notebooks/kaggle/kaggle_run.py output phrases02      # → results/kaggle/phrases02/

Kaggle limits: 12 h per run, ~30 GPU h per week; GPU = T4 (fp16 — the trainers use
GradScaler there, bf16 is Ampere+ only). Pushing creates a notebook version and runs it.
"""

import argparse
import json
import os
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_URL = "https://github.com/shravnchandr/Sign-Language-Translation.git"
DATASETS = ["shravnchandr/asl-is-lmdb", "shravnchandr/islr-checkpoints", "shravnchandr/wlasl-lmdb"]
KAGGLE = shlex.split(os.environ.get("KAGGLE_CLI", "uvx --with six kaggle"))
ROOT = Path(__file__).resolve().parents[2]


def kaggle(*args: str, check: bool = True) -> str:
    out = subprocess.run([*KAGGLE, *args], capture_output=True, text=True)
    if check and out.returncode:
        sys.exit(out.stderr or out.stdout)
    return out.stdout


def user() -> str:
    cfg = Path.home() / ".kaggle" / "kaggle.json"
    return os.environ.get("KAGGLE_USERNAME") or json.loads(cfg.read_text())["username"]


def notebook(ref: str, module: str, args: list[str], local_copy: bool = True) -> dict:
    def code(src: str) -> dict:
        return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
                "source": src.strip("\n").splitlines(True)}

    return {
        "cells": [
            {"cell_type": "markdown", "metadata": {},
             "source": [f"Generated by `notebooks/kaggle/kaggle_run.py` — `python -m {module}` "
                        f"at `{ref}`."]},
            code(f"""
import glob, os, subprocess, sys
REF, MODULE, ARGS, LOCAL_COPY = {ref!r}, {module!r}, {args!r}, {local_copy!r}
subprocess.run("pip install -q lmdb", shell=True, check=True)
subprocess.run(f"git clone -q {REPO_URL} /tmp/repo && git -C /tmp/repo checkout -q {{REF}}",
               shell=True, check=True)
import torch
print("repo", subprocess.run(["git", "-C", "/tmp/repo", "log", "--oneline", "-1"],
                             capture_output=True, text=True).stdout.strip())
print("torch", torch.__version__, "| CUDA", torch.cuda.is_available(),
      torch.cuda.get_device_name(0) if torch.cuda.is_available() else "", "| CPUs", os.cpu_count())
"""),
            code("""
def find(pattern):
    hits = sorted(glob.glob(f"/kaggle/input/**/{pattern}", recursive=True))
    return hits[0] if hits else None

paths = {
    "IS_LMDB_DIR": os.path.dirname(find("is.lmdb.mdb") or ""),
    "CKPT_DIR": os.path.dirname(os.path.dirname(find("fold0_graph/best_phase1.pth") or "/x/x")),
    "WLASL_DIR": os.path.dirname(find("wlasl.lmdb.mdb") or ""),
    "OUT": "/kaggle/working/out",
}
os.makedirs(paths["OUT"], exist_ok=True)
# /kaggle/input is slow for random reads: the phrase loader read ~125 ms per phrase from it
# (4 ms from a local disk). Copy the LMDB folders to local disk first (minutes, once per run).
import shutil, time
for key in ("IS_LMDB_DIR", "WLASL_DIR") if LOCAL_COPY else ():
    if paths[key]:
        t0, dst = time.time(), f"/tmp/{key.lower()}"
        shutil.copytree(paths[key], dst, dirs_exist_ok=True)
        print(f"copied {paths[key]} → {dst} in {time.time() - t0:.0f}s")
        paths[key] = dst
print(paths)
cmd = [sys.executable, "-u", "-m", MODULE] + [a.format(**paths) for a in ARGS]
print(" ".join(cmd))
"""),
            code("""
env = {**os.environ, "PYTHONPATH": "/tmp/repo/research/models"}
with open(f"{paths['OUT']}/run.log", "w") as log:
    proc = subprocess.Popen(cmd, env=env, cwd="/tmp/repo", stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True, bufsize=1)
    for line in proc.stdout:
        log.write(line)
        log.flush()
        if "it/s]" not in line and "s/it]" not in line:  # keep tqdm out of the notebook log
            print(line, end="")
rc = proc.wait()
print("exit code", rc)
assert rc == 0, f"command failed ({rc}); see out/run.log"
"""),
        ],
        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                    "name": "python3"}, "language_info": {"name": "python"}},
        "nbformat": 4, "nbformat_minor": 5,
    }


def push(a: argparse.Namespace) -> None:
    ref = a.ref or subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"],
                                  capture_output=True, text=True, check=True).stdout.strip()
    if not a.ref:
        ahead = subprocess.run(["git", "-C", str(ROOT), "branch", "-r", "--contains", ref],
                               capture_output=True, text=True).stdout.strip()
        if not ahead:
            sys.exit(f"HEAD {ref[:7]} is not pushed — the notebook clones from GitHub. Push first.")
    if not a.command:
        sys.exit("missing: -- <module> [args]")
    slug = f"{user()}/islr-{a.name}"
    with tempfile.TemporaryDirectory() as tmp:
        nb = Path(tmp) / f"islr-{a.name}.ipynb"
        nb.write_text(json.dumps(notebook(ref, a.command[0], a.command[1:], not a.no_copy), indent=1))
        meta = {"id": slug, "title": f"islr-{a.name}", "code_file": nb.name, "language": "python",
                "kernel_type": "notebook", "is_private": True, "enable_gpu": a.gpu,
                "enable_tpu": False, "enable_internet": True, "keywords": [],
                "dataset_sources": DATASETS + a.dataset, "kernel_sources": [],
                "competition_sources": [], "model_sources": []}
        (Path(tmp) / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
        extra = ["--accelerator", a.accelerator] if a.gpu else []
        print(kaggle("kernels", "push", "-p", tmp, *extra).strip())
    print(f"ref {ref[:7]} | python -m {' '.join(a.command)}")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = p.add_subparsers(dest="action", required=True)
    s = sub.add_parser("push")
    s.add_argument("name")
    s.add_argument("--gpu", action="store_true")
    s.add_argument("--accelerator", default="NvidiaTeslaT4")
    s.add_argument("--ref", help="git commit/branch to clone (default: local HEAD, must be pushed)")
    s.add_argument("--dataset", action="append", default=[], help="extra dataset source")
    s.add_argument("--no-copy", action="store_true",
                   help="read the LMDBs from /kaggle/input instead of a local copy")
    for name in ("status", "output"):
        s = sub.add_parser(name)
        s.add_argument("name")
    argv = sys.argv[1:]
    cut = argv.index("--") if "--" in argv else len(argv)  # everything after -- is the command
    a = p.parse_args(argv[:cut])
    a.command = argv[cut + 1 :]
    if a.action == "push":
        push(a)
    elif a.action == "status":
        print(kaggle("kernels", "status", f"{user()}/islr-{a.name}").strip())
    else:
        out = ROOT / "results" / "kaggle" / a.name
        out.mkdir(parents=True, exist_ok=True)
        print(kaggle("kernels", "output", f"{user()}/islr-{a.name}", "-p", str(out)).strip()[-500:])
        print(f"→ {out}")


if __name__ == "__main__":
    main()
