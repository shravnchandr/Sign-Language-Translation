"""Extract MediaPipe Holistic landmarks from the WLASL videos on Kaggle (CPU), sharded.

Replaces the single-session `preprocess-wlasl-mediapipe` notebook (whose worker-wide tracker
seeded each clip from the previous one, and whose MediaPipe version was not pinned) with the
shared extraction cell of `extract_aslcitizen.py`: fresh tracker per video, MediaPipe 0.10.14,
full-size frames as before, per-clip frame size and mirroring check.

Videos: Kaggle dataset `risangbaskoro/wlasl-processed` (`videos/<video_id>.mp4`, `WLASL_v0.3.json`);
every instance with a video file, all 2,000 glosses. WLASL is C-UDA (computational use).
Output per shard: `train_landmark_files/<video_id>.parquet` (competition format, same names as the
old extraction, so LMDB keys are unchanged) + `shard_<k>.csv` (path, participant = WLASL signer_id,
split, gloss, video, n_frames, width, height, lr_dx). Build the LMDBs from the shards with
`build_wlasl_lmdb --input-root` (mount this version's shards only).

Usage (from the repo root; the repo is cloned at the pushed HEAD):
  python scripts/extract_wlasl.py push --shards 1 --limit 40 --name extract-wlasl-smoke
  python scripts/extract_wlasl.py push --shards 4
  python scripts/extract_wlasl.py status --shards 4
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from extract_aslcitizen import cells_at, cells_digest  # noqa: E402
from kaggle_run import REPO_URL, ROOT, kaggle, user  # noqa: E402

DATASET = "risangbaskoro/wlasl-processed"

CELL_SELECT = """
meta = sorted(glob.glob("/kaggle/input/**/WLASL_v0.3.json", recursive=True))[0]
vdir = os.path.join(os.path.dirname(meta), "videos")
rows = []
for entry in json.load(open(meta)):
    for inst in entry["instances"]:
        src = f"{vdir}/{inst['video_id']}.mp4"
        if os.path.exists(src):
            rows.append({"src": src, "video": f"{inst['video_id']}.mp4", "gloss": entry["gloss"],
                         "participant": inst["signer_id"], "split": inst["split"]})
videos = pd.DataFrame(rows).drop_duplicates("video").sort_values("video").reset_index(drop=True)
mine = videos.iloc[SHARD::SHARDS]
if LIMIT:
    mine = mine.head(LIMIT)
print(f"{len(videos)} videos ({videos['gloss'].nunique()} glosses, {videos['participant'].nunique()} signers), "
      f"shard {SHARD}/{SHARDS}: {len(mine)}")
"""


def notebook(ref: str, shard: int, shards: int, limit: int) -> dict:
    c = {**cells_at(ref, "extract_aslcitizen.py", ("CELL_SETUP", "CELL_RUN")),
         **cells_at(ref, "extract_wlasl.py", ("CELL_SELECT",))}
    digest = cells_digest(c["CELL_SETUP"], c["CELL_SELECT"], c["CELL_RUN"])

    def code(src: str) -> dict:
        return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
                "source": src.strip("\n").splitlines(True)}

    head = (f"REF, SHARD, SHARDS, LIMIT, REPO_URL = {ref!r}, {shard}, {shards}, {limit}, {REPO_URL!r}\n"
            "MAX_SIDE, OUT = None, '/kaggle/working/wlasl_landmarks'\n")
    return {
        "cells": [
            {"cell_type": "markdown", "metadata": {},
             "source": [f"WLASL → MediaPipe landmarks, shard {shard}/{shards}. Generated by `scripts/extract_wlasl.py`; "
                        f"cells from commit {ref[:7]}, digest {digest}."]},
            code(head + c["CELL_SETUP"]), code(c["CELL_SELECT"] + c["CELL_RUN"]),
        ],
        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                     "language_info": {"name": "python"}},
        "nbformat": 4, "nbformat_minor": 5,
    }


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("action", choices=["push", "status"])
    p.add_argument("--shards", type=int, default=4)
    p.add_argument("--only", type=int, nargs="*", help="shard numbers (default: all)")
    p.add_argument("--limit", type=int, default=0, help="first N videos per shard (smoke test)")
    p.add_argument("--ref", help="commit to clone (default HEAD; must be pushed) — pin it for queued pushes")
    p.add_argument("--name", default="extract-wlasl", help="kernel name prefix")
    a = p.parse_args()
    shards = a.only if a.only else range(a.shards)
    if a.action == "status":
        for k in shards:
            print(k, kaggle("kernels", "status", f"{user()}/{a.name}-s{k}", check=False).strip())
        return
    ref = subprocess.run(["git", "-C", str(ROOT), "rev-parse", a.ref or "HEAD"], capture_output=True,
                         text=True, check=True).stdout.strip()
    if not subprocess.run(["git", "-C", str(ROOT), "branch", "-r", "--contains", ref],
                          capture_output=True, text=True).stdout.strip():
        sys.exit(f"HEAD {ref[:7]} is not pushed — the notebook clones from GitHub. Push first.")
    for k in shards:
        name = f"{a.name}-s{k}"
        with tempfile.TemporaryDirectory() as tmp:
            nb = notebook(ref, k, a.shards, a.limit)
            (Path(tmp) / f"{name}.ipynb").write_text(json.dumps(nb, indent=1))
            meta = {"id": f"{user()}/{name}", "title": name, "code_file": f"{name}.ipynb",
                    "language": "python", "kernel_type": "notebook", "is_private": True,
                    "enable_gpu": False, "enable_tpu": False, "enable_internet": True, "keywords": [],
                    "dataset_sources": [DATASET], "kernel_sources": [], "competition_sources": [],
                    "model_sources": [], "docker_image": cells_at(ref, "extract_aslcitizen.py", ("DOCKER",))["DOCKER"]}
            (Path(tmp) / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
            print(k, kaggle("kernels", "push", "-p", tmp).strip())


if __name__ == "__main__":
    main()
