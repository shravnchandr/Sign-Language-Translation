"""Extract MediaPipe Holistic landmarks from PopSign ASL v1.0 game videos on Kaggle (CPU), sharded.

PopSign ASL v1.0 (Starner et al., NeurIPS 2023 Datasets & Benchmarks; Georgia Tech): 250 signs —
the ASL Signs vocabulary — by 47 Deaf signers on Pixel 4A selfie cameras, 1944×2592 portrait.
Licensed **CC BY 4.0** at the source (signdata.cc.gatech.edu); credit it wherever a model trained
on it ships. The Kaggle mirror used here (mrgeislinger/popsign-asl-v1-0-game-*) labels some parts
BY-SA / BY-NC-SA — the source's license governs.

The four train datasets (signs A–E, F–M, N–S, T–Z; ~670 GB of mp4) are mounted, the videos listed
(`<sign>/<sign>/<participant>-<sign>-<timestamp>-0.mp4`) and --per-pair clips per (participant,
sign) taken, evenly spaced over that pair's recordings in file-name order; a shard takes every N-th
of them. Frames are downscaled to --max-side before MediaPipe (decoding 2592-px frames dominates
the time otherwise). Output as `extract_aslcitizen.py` (shared extraction cell): one
competition-format parquet per video + `shard_<k>.csv` (path, participant, split, gloss = the
PopSign folder name, video, n_frames, width, height, lr_dx — > 0 means unmirrored like ASL Signs).

PopSign comes from the same game as the Google ASL Signs data, so some signers likely overlap:
ASL Signs held-out scores are not clean for a model trained on it (use ASL Citizen / WLASL).

Usage (from the repo root; the repo is cloned at the pushed HEAD):
  python scripts/extract_popsign.py push --shards 1 --limit 40 --name extract-popsign-smoke
  python scripts/extract_popsign.py push --shards 12
  python scripts/extract_popsign.py status --shards 12
"""

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from extract_aslcitizen import cells_at, cells_digest  # noqa: E402
from kaggle_run import REPO_URL, ROOT, kaggle, user  # noqa: E402

DATASETS = [f"mrgeislinger/popsign-asl-v1-0-game-train-{r}-signs" for r in ("a-e", "f-m", "n-s", "t-z")]

CELL_SELECT = """
t0 = time.time()
rows = []
for d in sorted(glob.glob("/kaggle/input/**/popsign-asl-v1-0-game-train-*", recursive=True)):
    for dirpath, _, files in os.walk(d):
        for f in files:
            if f.endswith(".mp4"):
                sign = os.path.basename(dirpath)
                cut = f.find(f"-{sign}-")
                rows.append({"src": os.path.join(dirpath, f), "video": f, "gloss": sign,
                             "participant": f[:cut] if cut > 0 else f.split("-")[0]})
videos = pd.DataFrame(rows).sort_values("video").reset_index(drop=True)
print(f"{len(videos)} videos, {videos['participant'].nunique()} participants, {videos['gloss'].nunique()} "
      f"signs (listed in {time.time() - t0:.0f}s)")

def spaced(g):  # PER_PAIR recordings evenly spaced over the pair's sessions
    idx = np.unique(np.linspace(0, len(g) - 1, min(PER_PAIR, len(g))).round().astype(int))
    return g.iloc[idx]

picked = videos.groupby(["participant", "gloss"], group_keys=False).apply(spaced).sort_values("video")
picked = picked.reset_index(drop=True).assign(split="train")
mine = picked.iloc[SHARD::SHARDS]
if LIMIT:
    mine = mine.head(LIMIT)
print(f"{len(picked)} clips selected ({PER_PAIR} per participant × sign), shard {SHARD}/{SHARDS}: {len(mine)}")
"""


def notebook(ref: str, shard: int, shards: int, per_pair: int, max_side: int, limit: int) -> dict:
    c = {**cells_at(ref, "extract_aslcitizen.py", ("CELL_SETUP", "CELL_RUN")),
         **cells_at(ref, "extract_popsign.py", ("CELL_SELECT",))}
    digest = cells_digest(c["CELL_SETUP"], c["CELL_SELECT"], c["CELL_RUN"])

    def code(src: str) -> dict:
        return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
                "source": src.strip("\n").splitlines(True)}

    head = (f"REF, SHARD, SHARDS, PER_PAIR, LIMIT, REPO_URL = {ref!r}, {shard}, {shards}, {per_pair}, "
            f"{limit}, {REPO_URL!r}\nMAX_SIDE, OUT = {max_side or None}, '/kaggle/working/popsign_landmarks'\n")
    return {
        "cells": [
            {"cell_type": "markdown", "metadata": {},
             "source": [f"PopSign ASL v1.0 (CC BY 4.0) → MediaPipe landmarks, shard {shard}/{shards}. "
                        "Generated by `scripts/extract_popsign.py`; "
                        f"cells from commit {ref[:7]}, digest {digest}."]},
            code(head + c["CELL_SETUP"]), code(c["CELL_SELECT"] + c["CELL_RUN"]),
        ],
        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                     "language_info": {"name": "python"}},
        "nbformat": 4, "nbformat_minor": 5,
    }


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("action", choices=["push", "status"])
    p.add_argument("--shards", type=int, default=12)
    p.add_argument("--only", type=int, nargs="*", help="shard numbers (default: all)")
    p.add_argument("--per-pair", type=int, default=4, help="clips per (participant, sign)")
    p.add_argument("--max-side", type=int, default=1280, help="downscale frames to this long side (0 = off)")
    p.add_argument("--limit", type=int, default=0, help="first N videos per shard (smoke test)")
    p.add_argument("--ref", help="commit to clone (default HEAD; must be pushed) — pin it for queued pushes")
    p.add_argument("--name", default="extract-popsign", help="kernel name prefix")
    a = p.parse_args()
    shards = a.only if a.only else range(a.shards)
    if a.action == "status":
        for k in shards:
            print(k, kaggle("kernels", "status", f"{user()}/{a.name}-s{k}", check=False).strip())
        return
    ref = subprocess.run(["git", "-C", str(ROOT), "rev-parse", a.ref or "HEAD"], capture_output=True,
                         text=True, check=True).stdout.strip()
    if not subprocess.run(["git", "-C", str(ROOT), "branch", "-r", "--contains", ref],
                          capture_output=True, text=True).stdout.strip():
        sys.exit(f"HEAD {ref[:7]} is not pushed — the notebook clones from GitHub. Push first.")
    for k in shards:
        name = f"{a.name}-s{k}"
        with tempfile.TemporaryDirectory() as tmp:
            nb = notebook(ref, k, a.shards, a.per_pair, a.max_side, a.limit)
            (Path(tmp) / f"{name}.ipynb").write_text(json.dumps(nb, indent=1))
            meta = {"id": f"{user()}/{name}", "title": name, "code_file": f"{name}.ipynb",
                    "language": "python", "kernel_type": "notebook", "is_private": True,
                    "enable_gpu": False, "enable_tpu": False, "enable_internet": True, "keywords": [],
                    "dataset_sources": DATASETS, "kernel_sources": [], "competition_sources": [],
                    "model_sources": [], "docker_image": cells_at(ref, "extract_aslcitizen.py", ("DOCKER",))["DOCKER"]}
            (Path(tmp) / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
            print(k, kaggle("kernels", "push", "-p", tmp).strip())


if __name__ == "__main__":
    main()
